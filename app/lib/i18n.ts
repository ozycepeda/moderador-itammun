export const translations: Record<Language, Record<TranslationKey, string>> = { es, en };

export function isTranslationKey(value: unknown): value is TranslationKey {
  return typeof value === "string" && Object.prototype.hasOwnProperty.call(es, value);
}

export function interpolate(template: string, values: Record<string, string | number> = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}
